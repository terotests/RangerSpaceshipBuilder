//! The ship tool:
//!
//!   ship glb <recipe.ship.json> [out.glb]   one ship as a .glb (--textures: with PNG maps)
//!   ship info <recipe.ship.json>...         triangles, size, warnings
//!   ship textures <out>                     the built-in materials' maps as PNG files
//!   ship pack <dir> <out> [--textures]      every *.ship.json in <dir> as a ship pack:
//!                                           <out>/ships.json (+ ships.ts), <id>.glb, <id>.ship.json
//!
//! A ship pack is what RangerGames reads (docs/format.md): copy <out> into a
//! game's folder, or run `ship pack ships ../RangerGames/games/<game>/ships`.

use std::fs;
use std::path::Path;

fn id_of(path: &Path) -> String {
    let name = path.file_name().unwrap().to_string_lossy().to_string();
    name.trim_end_matches(".ship.json").to_string()
}

fn build(path: &Path) -> ship_core::recipe::Ship {
    let text = fs::read_to_string(path).unwrap_or_else(|e| panic!("{}: {}", path.display(), e));
    let ship = ship_core::recipe::build(&text);
    if !ship.error.is_empty() {
        eprintln!("{}: {}", path.display(), ship.error);
        std::process::exit(1);
    }
    for w in ship.warnings.iter() {
        eprintln!("{}: {}", path.display(), w);
    }
    ship
}

fn recipes(dir: &Path) -> Vec<std::path::PathBuf> {
    let mut v: Vec<_> = fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("{}: {}", dir.display(), e))
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.to_string_lossy().ends_with(".ship.json"))
        .collect();
    v.sort();
    v
}

fn main() {
    let all: Vec<String> = std::env::args().collect();
    let textures = all.iter().any(|a| a == "--textures");
    let args: Vec<String> = all.into_iter().filter(|a| a != "--textures").collect();
    let cmd = args.get(1).map(|s| s.as_str()).unwrap_or("");
    match cmd {
        "glb" if args.len() >= 3 => {
            let src = Path::new(&args[2]);
            let out = args.get(3).cloned().unwrap_or_else(|| format!("{}.glb", id_of(src)));
            let ship = build(src);
            fs::write(&out, ship_core::gltf::write_glb_with(&ship, textures)).unwrap();
            println!("{} -> {} ({} triangles)", src.display(), out, ship.mesh.count());
        }
        "info" if args.len() >= 3 => {
            for a in &args[2..] {
                let p = Path::new(a);
                let files = if p.is_dir() { recipes(p) } else { vec![p.to_path_buf()] };
                for f in files {
                    println!("{}", build(&f).info());
                }
            }
        }
        "pack" if args.len() >= 4 => {
            let dir = Path::new(&args[2]);
            let out = Path::new(&args[3]);
            fs::create_dir_all(out).unwrap();
            let mut entries = Vec::new();
            for f in recipes(dir) {
                let id = id_of(&f);
                let ship = build(&f);
                let glb = ship_core::gltf::write_glb_with(&ship, textures);
                fs::write(out.join(format!("{}.glb", id)), &glb).unwrap();
                fs::copy(&f, out.join(format!("{}.ship.json", id))).unwrap();
                let b = ship.mesh.bounds();
                let size = b[1].sub(b[0]);
                let center = b[0].add(b[1]).mul(0.5);
                let radius = size.len() * 0.5;
                use ship_core::json::{num, quote};
                entries.push(format!(
                    "    {{ \"id\": {}, \"name\": {}, \"class\": {}, \"length\": {}, \"model\": {}, \"recipe\": {}, \"triangles\": {}, \"size\": [{}, {}, {}], \"center\": [{}, {}, {}], \"radius\": {} }}",
                    quote(&id), quote(&ship.name), quote(&ship.class), num(ship.length),
                    quote(&format!("{}.glb", id)), quote(&format!("{}.ship.json", id)), ship.mesh.count(),
                    num(size.x), num(size.y), num(size.z), num(center.x), num(center.y), num(center.z), num(radius)
                ));
                println!("{:<14} {:<10} {:>6} triangles {:>8} bytes", id, ship.class, ship.mesh.count(), glb.len());
            }
            let manifest = format!(
                "{{\n  \"format\": \"ranger-ship-pack\",\n  \"version\": 1,\n  \"forward\": \"+z\",\n  \"up\": \"+y\",\n  \"ships\": [\n{}\n  ]\n}}\n",
                entries.join(",\n")
            );
            fs::write(out.join("ships.json"), &manifest).unwrap();
            // the same list as a module a RangerGames game imports: import { SHIPS } from "ships/ships"
            let module = format!("// Generated by RangerSpaceshipBuilder (ship pack). Do not edit.\nexport const PACK = {};\nexport const SHIPS = PACK.ships;\n", manifest.trim_end());
            fs::write(out.join("ships.ts"), module).unwrap();
            println!("{} ships -> {}", entries.len(), out.display());
        }
        "textures" if args.len() >= 3 => {
            // every built-in material's maps as PNG files, to look at
            let out = Path::new(&args[2]);
            fs::create_dir_all(out).unwrap();
            for name in ship_core::material::PATTERNS.split(' ') {
                let m = ship_core::material::builtin(name);
                let set = ship_core::texture::generate(&m, 256);
                for (kind, data) in [("base", &set.base), ("orm", &set.orm), ("normal", &set.normal)] {
                    fs::write(out.join(format!("{}_{}.png", name, kind)), ship_core::png::write_rgb(set.size, set.size, data)).unwrap();
                }
            }
            println!("{} materials -> {}", ship_core::material::PATTERNS.split(' ').count(), out.display());
        }
        _ => {
            eprintln!("usage:\n  ship glb <recipe.ship.json> [out.glb]\n  ship info <recipe.ship.json|dir>...\n  ship pack <dir> <out> [--textures]\n  ship textures <out>");
            std::process::exit(2);
        }
    }
}
